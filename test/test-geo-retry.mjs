import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const scripts=[], calls=[];
const window={};
const env={window,document:{createElement:()=>({}),head:{appendChild:s=>scripts.push(s)}}};
vm.runInNewContext(readFileSync(new URL('../js/geo.js',import.meta.url),'utf8'),env);
const geo=env.Geo || window.Geo;
geo.ensure(error=>calls.push(error ? 'failed' : 'loaded'));
geo.ensure(error=>calls.push(error ? 'also failed' : 'also loaded'));
assert.equal(scripts.length,1);
scripts[0].onerror();
assert.deepEqual(calls,['failed','also failed']);
geo.ensure(error=>calls.push(error ? 'retry failed' : 'retry loaded'));
assert.equal(scripts.length,2);
window.CITY_DB=[];
scripts[1].onload();
geo.ensure(error=>calls.push(error ? 'cached failed' : 'cached loaded'));
assert.equal(scripts.length,2);
assert.deepEqual(calls,['failed','also failed','retry loaded','cached loaded']);
console.log('  ok   failed city loading releases all waiters and permits a successful retry');
